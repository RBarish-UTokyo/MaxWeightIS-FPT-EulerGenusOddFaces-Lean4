#!/usr/bin/env python3
"""Generate Challenge.lean from the authoritative statement modules.

The bodies of `MWIS/Statement.lean` (machine, cost, surfaces, drawings, input
encoding and output reading) and `MWIS/FPTStatement.lean` (the fixed-parameter
claim) are copied verbatim, followed by the single target
`MWIS.Spec.fpt_claim`, stated with `sorry`. Comparator checks that every
constant used by the target is the same kernel declaration in the solution
environment, so an edited or stale copy is rejected rather than trusted.

Usage: python3 scripts/generate_challenge.py [--check]
"""

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "MWIS"
MARKER = "@[expose] public section\n"

HEADER = '''-- GENERATED by scripts/generate_challenge.py from MWIS/Statement.lean and
-- MWIS/FPTStatement.lean; do not edit by hand.
module

public import Mathlib

/-!
# Challenge: fixed-parameter maximum-weight independent set on surfaces

This file is the statement a reader should audit. It states that one fixed
program for an explicit sixteen-register pointer machine computes a
maximum-weight independent set of every graph drawn in a closed surface, for
arbitrary integer vertex weights, using at most

  `2 ^ (c · (p · size p + 1)) · (N · size M) ^ c`

bit operations for one absolute constant `c`. Here `p = γ + k`, `γ` is the Euler
genus of the surface, `k` is the number of complementary regions of the drawing
whose total boundary length is odd, `N = |V| + |E| + 1`, `M = max(1, max_v |w_v|)`
and `size x = ⌈log₂(x + 1)⌉`. This is `2^{O(p log(p+1))} · poly(N, log(M+1))`
with an absolute polynomial exponent.

The file is a verbatim copy of the bodies of the project modules
`MWIS/Statement.lean` and `MWIS/FPTStatement.lean`, followed by the target
`MWIS.Spec.fpt_claim`, omitting only the inherited XP statement `MainClaim`,
which the target does not use. The machine, its cost, the surface model and the
input encoding are those of the registered entry PALOMAR-2026-10-22-000006 v1.

Reading order: memory cells, events and runs; the explicit bit-stack cost of
calls (`stackBitCost`); the register machine and its framed interpreter
(`FramedExec`); flags, closed-surface maps, faces, Euler genus and
complementary regions (`Map`); drawings and their placement in a map
(`Drawing.In`); independent and maximum sets; the input heap (`encode`), the
output reading (`Outputs`) and runs (`Runs`); finally `FPTClaim`.
-/

@[expose] public section

'''

TARGET = '''
/-- **Target.** The fixed-parameter main claim. -/
theorem MWIS.Spec.fpt_claim : MWIS.Spec.FPTClaim := by
  sorry

end
'''


def body(path):
    """Everything after the `@[expose] public section` line, without the final `end`."""
    text = path.read_text()
    start = text.index(MARKER) + len(MARKER)
    rest = text[start:].rstrip()
    assert rest.endswith("end"), path
    return rest[: -len("end")].rstrip() + "\n"


def without_main_claim(text):
    """Drop the inherited XP `MainClaim` (unused by the target) and its docstring."""
    start = text.index("/-- **Main claim**")
    stop = text.index("end MWIS.Spec", start)
    return text[:start].rstrip() + "\n\n" + text[stop:]


def render():
    return (HEADER + without_main_claim(body(SRC / "Statement.lean")) + "\n" +
            body(SRC / "FPTStatement.lean") + TARGET)


def main():
    out = render()
    target = ROOT / "Challenge.lean"
    if "--check" in sys.argv[1:]:
        if target.read_text() != out:
            sys.exit("Challenge.lean is not the generated statement")
        print("Challenge.lean matches its sources")
        return
    target.write_text(out)
    print(f"wrote {target.relative_to(ROOT)} ({out.count(chr(10))} lines, {len(out.encode())} bytes)")


if __name__ == "__main__":
    main()
